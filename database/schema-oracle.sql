-- 1. App Users (Role-Based Access: Admin, Claims Officer, Finance Officer)
CREATE TABLE APP_USERS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(60) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(150) NOT NULL,
    FULL_NAME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    ROLE VARCHAR2(40) NOT NULL, -- ROLE_ADMIN, ROLE_CLAIMS_OFFICER, ROLE_FINANCE_OFFICER
    PHONE_NUMBER VARCHAR2(30),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_USER_ROLE CHECK (ROLE IN ('ROLE_ADMIN', 'ROLE_CLAIMS_OFFICER', 'ROLE_FINANCE_OFFICER', 'ROLE_CUSTOMER_REP'))
);

-- 2. Customers
CREATE TABLE CUSTOMERS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(60) NOT NULL,
    LAST_NAME VARCHAR2(60) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PHONE VARCHAR2(30) NOT NULL,
    STREET_ADDRESS VARCHAR2(255),
    CITY VARCHAR2(100),
    STATE_PROVINCE VARCHAR2(60),
    POSTAL_CODE VARCHAR2(20),
    CREDIT_SCORE NUMBER(4) NOT NULL,
    ANNUAL_INCOME NUMBER(12, 2) NOT NULL,
    EMPLOYMENT_STATUS VARCHAR2(40) NOT NULL, -- EMPLOYED, SELF_EMPLOYED, RETIRED, OTHER
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_CREDIT_SCORE CHECK (CREDIT_SCORE BETWEEN 300 AND 850)
);

-- 3. Vehicles
CREATE TABLE VEHICLES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    VIN VARCHAR2(17) NOT NULL UNIQUE,
    MAKE VARCHAR2(60) NOT NULL,
    MODEL VARCHAR2(60) NOT NULL,
    MODEL_YEAR NUMBER(4) NOT NULL,
    MILEAGE NUMBER(8) NOT NULL,
    PURCHASE_PRICE NUMBER(12, 2) NOT NULL,
    PURCHASE_DATE DATE NOT NULL,
    VEHICLE_CONDITION VARCHAR2(30) DEFAULT 'USED' NOT NULL, -- NEW, USED, CERTIFIED_PRE_OWNED
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL, -- ACTIVE, INACTIVE, TRANSFERRED
    CUSTOMER_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_VEHICLE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID) ON DELETE CASCADE,
    CONSTRAINT CHK_VIN_LEN CHECK (LENGTH(VIN) = 17)
);

-- 4. Warranty Plans
CREATE TABLE WARRANTY_PLANS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PLAN_CODE VARCHAR2(30) NOT NULL UNIQUE,
    PLAN_NAME VARCHAR2(100) NOT NULL,
    PLAN_TYPE VARCHAR2(40) NOT NULL, -- POWERTRAIN, COMPREHENSIVE, BUMPER_TO_BUMPER, EV_DRIVETRAIN
    DESCRIPTION VARCHAR2(1000) NOT NULL,
    DURATION_MONTHS NUMBER(3) NOT NULL,
    MAX_MILEAGE_COVERAGE NUMBER(8) NOT NULL,
    DEDUCTIBLE_AMOUNT NUMBER(10, 2) NOT NULL,
    BASE_PREMIUM NUMBER(10, 2) NOT NULL,
    MAX_CLAIM_LIMIT NUMBER(10, 2) NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 5. Warranty Contracts
CREATE TABLE WARRANTY_CONTRACTS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONTRACT_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    CUSTOMER_ID NUMBER NOT NULL,
    VEHICLE_ID NUMBER NOT NULL,
    PLAN_ID NUMBER NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    START_MILEAGE NUMBER(8) NOT NULL,
    MAX_MILEAGE NUMBER(8) NOT NULL,
    TOTAL_PREMIUM NUMBER(10, 2) NOT NULL,
    MONTHLY_PREMIUM NUMBER(10, 2) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL, -- ACTIVE, EXPIRED, CANCELLED, CLAIM_SUSPENDED
    RENEWAL_COUNT NUMBER(3) DEFAULT 0 NOT NULL,
    NOTES VARCHAR2(500),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CONTRACT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID),
    CONSTRAINT FK_CONTRACT_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(ID),
    CONSTRAINT FK_CONTRACT_PLAN FOREIGN KEY (PLAN_ID) REFERENCES WARRANTY_PLANS(ID),
    CONSTRAINT CHK_CONTRACT_STATUS CHECK (STATUS IN ('ACTIVE', 'EXPIRED', 'CANCELLED', 'CLAIM_SUSPENDED'))
);

-- 6. Claims Management
CREATE TABLE CLAIMS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CLAIM_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    CONTRACT_ID NUMBER NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    VEHICLE_ID NUMBER NOT NULL,
    INCIDENT_DATE DATE NOT NULL,
    CURRENT_MILEAGE NUMBER(8) NOT NULL,
    DESCRIPTION VARCHAR2(1500) NOT NULL,
    REPAIR_SHOP_NAME VARCHAR2(120) NOT NULL,
    REPAIR_ESTIMATE NUMBER(10, 2) NOT NULL,
    APPROVED_AMOUNT NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    DEDUCTIBLE_PAID NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'SUBMITTED' NOT NULL, -- SUBMITTED, UNDER_REVIEW, APPROVED, REJECTED, PAID
    REJECTION_REASON VARCHAR2(500),
    OFFICER_NOTES VARCHAR2(1000),
    REVIEWER_ID NUMBER,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CLAIM_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES WARRANTY_CONTRACTS(ID),
    CONSTRAINT FK_CLAIM_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID),
    CONSTRAINT FK_CLAIM_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(ID),
    CONSTRAINT FK_CLAIM_REVIEWER FOREIGN KEY (REVIEWER_ID) REFERENCES APP_USERS(ID),
    CONSTRAINT CHK_CLAIM_STATUS CHECK (STATUS IN ('SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED', 'PAID'))
);

-- 7. Financing & Leasing Applications
CREATE TABLE FINANCING_APPLICATIONS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    APPLICATION_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    CUSTOMER_ID NUMBER NOT NULL,
    VEHICLE_ID NUMBER NOT NULL,
    VEHICLE_PRICE NUMBER(12, 2) NOT NULL,
    DOWN_PAYMENT NUMBER(12, 2) NOT NULL,
    LOAN_AMOUNT NUMBER(12, 2) NOT NULL,
    LOAN_TERM_MONTHS NUMBER(3) NOT NULL,
    INTEREST_RATE NUMBER(5, 2) NOT NULL,
    CALCULATED_EMI NUMBER(10, 2) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'SUBMITTED' NOT NULL, -- SUBMITTED, UNDER_REVIEW, APPROVED, REJECTED
    MONTHLY_INCOME NUMBER(12, 2) NOT NULL,
    DEBT_TO_INCOME_RATIO NUMBER(5, 2) NOT NULL,
    CREDIT_TIER VARCHAR2(30) NOT NULL, -- TIER_1_EXCELLENT, TIER_2_GOOD, TIER_3_FAIR, HIGH_RISK
    OFFICER_NOTES VARCHAR2(1000),
    REVIEWER_ID NUMBER,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_FINANCE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID),
    CONSTRAINT FK_FINANCE_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(ID),
    CONSTRAINT FK_FINANCE_REVIEWER FOREIGN KEY (REVIEWER_ID) REFERENCES APP_USERS(ID),
    CONSTRAINT CHK_FINANCE_STATUS CHECK (STATUS IN ('SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED'))
);

-- 8. Audit Logs
CREATE TABLE AUDIT_LOGS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ENTITY_NAME VARCHAR2(60) NOT NULL,
    ENTITY_ID NUMBER NOT NULL,
    ACTION_TYPE VARCHAR2(40) NOT NULL, -- CREATE, UPDATE, STATUS_CHANGE, APPROVE, REJECT
    PERFORMED_BY VARCHAR2(60) NOT NULL,
    LOG_TIMESTAMP TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DETAILS VARCHAR2(2000)
);

-- Indexes for high-throughput enterprise performance
CREATE INDEX IDX_CUST_EMAIL ON CUSTOMERS(EMAIL);
CREATE INDEX IDX_VEH_VIN ON VEHICLES(VIN);
CREATE INDEX IDX_VEH_CUST ON VEHICLES(CUSTOMER_ID);
CREATE INDEX IDX_CONT_CUST ON WARRANTY_CONTRACTS(CUSTOMER_ID);
CREATE INDEX IDX_CONT_STATUS ON WARRANTY_CONTRACTS(STATUS);
CREATE INDEX IDX_CLAIM_STATUS ON CLAIMS(STATUS);
CREATE INDEX IDX_CLAIM_CONT ON CLAIMS(CONTRACT_ID);
CREATE INDEX IDX_FIN_STATUS ON FINANCING_APPLICATIONS(STATUS);
CREATE INDEX IDX_AUDIT_ENTITY ON AUDIT_LOGS(ENTITY_NAME, ENTITY_ID);
